/**
 * Markers of a bot-challenge or block interstitial. When a host serves one of
 * these, the response describes the edge, not the site, so nothing in it counts
 * as evidence about the platform.
 */
const INTERSTITIAL_MARKERS =
  /cf_chl_opt|__cf_chl|Just a moment\.\.\.|Attention Required!|Sorry, you have been blocked|Checking your browser before accessing|Enable JavaScript and cookies to continue/i;

/**
 * Cloudflare injects this script into ordinary successful responses as part of
 * bot scoring, so on its own it says nothing. It only indicates an interstitial
 * when it arrives with a status that means the request was refused.
 */
const CHALLENGE_SCRIPT = /cdn-cgi\/challenge-platform/i;
const REFUSAL_STATUSES = new Set([403, 429, 503]);

export function looksLikeInterstitial(body: string, status: number | null): boolean {
  if (INTERSTITIAL_MARKERS.test(body)) return true;
  return status !== null && REFUSAL_STATUSES.has(status) && CHALLENGE_SCRIPT.test(body);
}

