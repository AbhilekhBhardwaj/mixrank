import type { RobotsGate } from "./robots";
import type { Confidence, ProbeResult, TechCategory, TechMatch } from "@/lib/types";

interface HintRule {
  name: string;
  category: TechCategory;
  /**
   * Every pattern must match. Multi-pattern rules exist because single generic
   * directory names (/components/, /modules/, /checkouts/) appear in plenty of
   * robots.txt files that have nothing to do with the platform that popularised
   * them; requiring the co-occurring set is what makes them evidence.
   */
  patterns: RegExp[];
  label: string;
  confidence: Confidence;
}

interface PathProbe {
  path: string;
  name: string;
  category: TechCategory;
  /** Statuses that suggest the resource actually exists. */
  accept: number[];
  /** Body pattern that upgrades the match from "path exists" to "confirmed". */
  confirm: RegExp;
}

